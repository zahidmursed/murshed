class TranslitResult {
  final String english;
  final String arabic;
  final int tokens;
  final int unknown;

  const TranslitResult(this.english, this.arabic, this.tokens, this.unknown);

  bool get isEmpty => tokens == 0;
  bool get allKnown => tokens > 0 && unknown == 0;
}

