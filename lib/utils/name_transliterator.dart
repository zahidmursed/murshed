  /// বিল্ড করা হয় — তাই ফাইলের কী-তে precomposed য়/ড়/ঢ় থাকলেও
  /// (decomposed) টোকেনে মিস হয় না, উল্টোটাও নয়। লুকআপ সবসময়
  /// এই নরমালাইজড ম্যাপেই চলবে (_aliases/_dict সরাসরি নয়)।
  static final Map<String, String> _aliasesN = _normKeys(_aliases);
  static final Map<String, (String, String)> _dictN = _normKeys(_dict);

  static Map<String, V> _normKeys<V>(Map<String, V> src) {
    final out = <String, V>{};
    src.forEach((k, v) => out.putIfAbsent(normalizeYaRa(k), () => v));
    return out;
  }

