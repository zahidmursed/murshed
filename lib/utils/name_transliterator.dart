  /// টোকেন → গ্রাফিম-ক্লাস্টার তালিকা।
  /// প্রতিটি ক্লাস্টার: ব্যঞ্জন = [লিপি, মাত্রা], স্বরবর্ণ = [লিপি]।
  static List<List<String>> _clusters(
      String token,
      Map<String, String> cMap,
      Map<String, String> vMap,
      Map<String, String> signMap,
      Map<String, String> nukta) {
    final units = token.runes.map(String.fromCharCode).toList();
    final out = <List<String>>[];
    var i = 0;
    while (i < units.length) {
      final ch = units[i];
      if (cMap.containsKey(ch)) {
        var lat = cMap[ch]!;
        var j = i + 1;
        // নুকতা (য় ড় ঢ়…)
        if (j < units.length && units[j] == '়' && nukta.containsKey(ch)) {
          lat = nukta[ch]!;
          j++;
        }
        // যুক্তবর্ণ (্)
        while (j + 1 < units.length &&
            units[j] == '্' &&
            cMap.containsKey(units[j + 1])) {
          final nc = units[j + 1];
          var piece = cMap[nc]!;
          j += 2;
          if (j < units.length && units[j] == '়' && nukta.containsKey(nc)) {
            piece = nukta[nc]!;
            j++;
          }
          lat += piece;
        }
        var matra = '';
        if (j < units.length && signMap.containsKey(units[j])) {
          matra = signMap[units[j]]!;
          j++;
        }
        out.add([lat, matra]);
        i = j;
      } else if (vMap.containsKey(ch)) {
        out.add([vMap[ch]!]);
        i++;
      } else {
        // অজানা অক্ষর যেমন আছে — কিন্তু En/Ar ম্যাপে নেই এমন বাংলা মাত্রা/চিহ্ন
        // কখনো আউটপুটে ফাঁস হতে দিই না (ঁ ্  ় ZWJ/ZWNJ …): নইলে ইংরেজি/আরবী
        // ঘরে বাংলা ঢুকে ভাঙা মান তৈরি হয়।
        if (!_unmappedBengaliMark(ch)) out.add([ch]);
        i++;
      }
    }
    return out;
  }

  /// বাংলা মাত্রা/চিহ্ন যেগুলোর En/Ar ম্যাপ নেই — নিয়ম-আউটপুটে বাদ যায়।
  static bool _unmappedBengaliMark(String ch) => BengaliText.isUnmappedMark(ch);

  /// ল্যাটিন নিয়ম: inherent 'অ' — শব্দ-শেষে নেই; ব্যঞ্জন-রানের ভেতরে
  /// (পরের ব্যঞ্জনও মাত্রাহীন) শব্দারম্ভ ছাড়া বাদ; নইলে 'a'।
  static String _ruleLatin(String token) {
    final parts = _clusters(token, _latinC, _latinV, _latinSign, _latinNukta);
    final sb = StringBuffer();
    for (var k = 0; k < parts.length; k++) {
      final p = parts[k];
      if (p.length == 1) {
        sb.write(p[0]);
        continue;
      }
      if (p[1].isNotEmpty) {
        sb.write(p[0]);
        sb.write(p[1]);
      } else if (k == parts.length - 1) {
        sb.write(p[0]); // শব্দ-শেষ — inherent স্বর নেই
      } else {
        final nextIsBare = parts[k + 1].length == 2 && parts[k + 1][1].isEmpty;
        if (nextIsBare && k > 0) {
          sb.write(p[0]); // রানের মাঝে
        } else {
          sb.write(p[0]);
          sb.write('a'); // রানের শেষ / শব্দারম্ভ
        }
      }
    }
    return sb.toString();
  }

  /// আরবী নিয়ম: **CLDR/ICU `InterIndic_Arabic` টেবিলের পোর্ট**
  /// ([InterIndicArabic]) — আগের হাতের ম্যাপের চেয়ে অনেক বেশি প্রমিত
  /// (ক→ك, খ→كه, গ→ج, প→ب; অনুস্বার/চন্দ্রবিন্দু→ن; শব্দ-শুরুতে ই→إ;
  /// হসন্ত বাদ; একাধিক alif সংকুচিত)।
  static String _ruleArabic(String token) =>
      InterIndicArabic.transliterate(token);

  /// টুল/টেস্টের জন্য: নরমালাইজ + অ্যালিয়াস-সমাধান করা লুকআপ-কী।
  static String canonicalToken(String token) {
    final t = normalizeYaRa(token);
    return _aliasesN[t] ?? t;
  }

  /// হাতে-লেখা ডিকশনারির এন্ট্রি (কর্পাস-টুলে তুলনা/merge-এর জন্য)।
  static (String, String)? dictEntry(String token) => _dictN[canonicalToken(token)];

  /// হাতে-লেখা ডিকশনারির সব কী (কর্পাস-টুলে merge-এর জন্য)।
  static Iterable<String> get dictTokens => _dict.keys;

  /// টোকেন (সংক্ষেপ-স্বাভাবিকীকরণের পর) ডিকশনারিতে আছে কি না —
  /// ডেটাসেট বিশ্লেষণ/টেস্টে ব্যবহারের জন্য পাবলিক API।
  /// ইনপুটও নরমালাইজ হয় — precomposed/decomposed য়-রূপভেদ মিস হয় না।
  static bool isKnownToken(String token) {
    final t = canonicalToken(token);
    return _dictN.containsKey(t);
  }

  /// ক্যাশ-কী: সংক্ষেপ-স্বাভাবিকীকরণের পর টোকেন-স্পেস-জোড়া।
  /// "মোঃ আব্দুল্লাহ", "মো: আব্দুল্লাহ", "মোঃআব্দুল্লাহ" → একই কী —
  /// একবার নিশ্চিত করা নাম রূপভেদ নির্বিশেষে পরেরবারও ম্যাচ করে।
  static String cacheKey(String banglaName) {
    return tokenize(banglaName).map((t) => _aliasesN[t] ?? t).join(' ');
  }

  /// পূর্ণ নাম → টোকেন তালিকা (সংক্ষেপ-বিভাজনসহ)।
  /// "মোঃআব্দুল্লাহ" (স্পেস ছাড়া) → ['মো:', 'আব্দুল্লাহ']।
  static List<String> tokenize(String name) {
    // ফিক্স: নরমালাইজেশন এখানেই চালানো হয় — precomposed য়/ড়/়, চন্দ্রবিন্দু,
    // ZWJ/ZWNJ স্বাভাবিক না হলে ডিকশনারি-মিস হয় ও নিয়ম-ফলব্যাকে কাঁচা বাংলা
    // অক্ষর En/Ar ঘরে ফাঁস করে (ডেটাসেট স্ক্যান: ৪২৩৮ নামের মধ্যে ৮৮৩টি)।
    final cleaned = normalizeYaRa(name).trim();
    if (cleaned.isEmpty) return const [];
    final out = <String>[];
    final prefixRe = RegExp(
        r'^(মোঃ|মো:|মুহা:|মুহাঃ|মোসাঃ|মোছাঃ|মোসা:|মোছা:|আ:|আঃ|মাওঃ|ডঃ|ডা:)(.+)$');
    for (final raw in cleaned.split(RegExp(r'\s+'))) {
      final m = prefixRe.firstMatch(raw);
      if (m != null) {
        out.add(m.group(1)!);
        out.add(m.group(2)!);
      } else {
        out.add(raw);
      }
    }
    return out;
  }

  /// বাংলা পূর্ণনাম থেকে ইংরেজি + আরবী লিপ্যন্তর।
  static TranslitResult transliterate(String banglaName) {
    final tokens = tokenize(banglaName);
    if (tokens.isEmpty) return const TranslitResult('', '', 0, 0);
    final en = <String>[];
    final ar = <String>[];
    var unknown = 0;
    for (final raw in tokens) {
      final t = _aliasesN[raw] ?? raw;
      // কর্পাস (২১k ভোট-যাচাইকৃত) → হাতে-লেখা ডিকশনারি → নিয়ম-fallback।
      final hit = _corpusN[t] ?? _dictN[t];
      if (hit != null) {
        en.add(hit.$1);
        ar.add(hit.$2);
      } else {
        unknown++;
        en.add(_ruleLatin(t));
        ar.add(_ruleArabic(t));
      }
    }
    // শেষ ভরসা (সেফটি নেট): En/Ar ঘরে কোনো বাংলা অক্ষর থেকে গেলে বাদ — ভবিষ্যতে
    // অজানা কোনো চিহ্নও এভাবে ডিকশনারি ঘরে ঢুকতে পারবে না।
    return TranslitResult(
      _stripBengali(en.join(' ')),
      _stripBengali(ar.join(' ')),
      tokens.length,
      unknown,
    );
  }

  /// বাংলা ব্লকের অক্ষর বাদ দিয়ে বাড়তি স্পেস পরিষ্কার করে।
  static String _stripBengali(String s) {
    if (!containsBengali(s)) return s;
    final buf = StringBuffer();
    for (final r in s.runes) {
      if (r >= 0x0980 && r <= 0x09FF) continue;
      buf.writeCharCode(r);
    }
    return buf.toString().replaceAll(RegExp(r'\s{2,}'), ' ').trim();
  }
