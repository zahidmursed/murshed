  /// হাতে-লেখা ডিকশনারি মার্জড) — এটিই প্রাথমিক লুকআপ; হাতে-লেখা _dict শুধু
  /// ফলব্যাক (corpus-এ না থাকা এন্ট্রির জন্য)।
  static final Map<String, (String, String)> _corpusN = _normPairs(kNameCorpus);

  static Map<String, (String, String)> _normPairs(Map<String, List<String>> src) {
    final out = <String, (String, String)>{};
    src.forEach((k, v) {
      out.putIfAbsent(normalizeYaRa(k), () => (v[0], v[1]));
    });
    return out;
  }

